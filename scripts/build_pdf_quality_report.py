    # 校正初筛：重复背景图会让原始图像面积规则误报所有页面。
    # 仅在风险统计中排除每份文档至少一半页面重复出现的图像；它们不因此被确认为无意义。
    for item in data['documents']:
        with pymupdf.open(ROOT / 'data/pdfs' / item['filename']) as doc:
            frequency = Counter()
            for p in doc:
                frequency.update({i['digest'] for i in p.get_image_info(hashes=True)})
            common = {key for key, count in frequency.items() if count >= max(3, math.ceil(len(doc)*.5))}
            subset = [r for r in rows if r['filename'] == item['filename']]
            for row, page in zip(subset, doc):
                text = page.get_text('text', sort=True)
                content_area = min(1., sum((pymupdf.Rect(i['bbox']) & page.rect).get_area() for i in page.get_image_info(hashes=True) if i['digest'] not in common) / page.rect.get_area())
                row['content_image_area_ratio'] = round(content_area, 4)
                flags = [f for f in row['flags'].split('；') if f and f != '图表/公式/图片内容可能未被纯文本保留']
                if content_area >= .12 or row['drawing_count'] >= 10 or sum(c in '∑∫√≤≥±αβγδθλμσπ∞≈' for c in text) >= 2:
                    flags.append('图表/公式/图片内容可能未被纯文本保留')
                if len(text) >= 100 and 1-row['nonspace_chars']/len(text) > .6:
                    flags.append('空白字符占比过高(>60%)')
                if row['key'] in VISUAL and VISUAL[row['key']][0] == '异常':
                    flags.append('已查看PNG发现异常')
                row['flags'] = '；'.join(flags)
                row['visual_review'] = VISUAL.get(row['key'], ('未抽查', ''))[0] if row['nonspace_chars'] else '专项查看'
